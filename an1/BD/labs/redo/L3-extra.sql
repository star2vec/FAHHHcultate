SELECT u.id_utilizator, u.nume, continut, TO_CHAR(data_postarii, 'DD.MM.YYYY')
from utilizatori u join prieteni p1 on (u.id_utilizator = p1.id_user1)
                   join prieteni p2 on (u.id_utilizator = p2.id_user2)
                   left join postari p on (u.id_utilizator = p.id_user)
WHERE p1.id_user2 = 1 AND p2.id_user1 = 1
AND TO_char(data_postarii, 'MON') = 'MAR' AND TO_char(data_postarii, 'YYYY') = 2024;


