-- Tabelul utilizatori
CREATE TABLE utilizatori (
    id_utilizator NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nume VARCHAR2(100) NOT NULL
);

-- Tabelul prieteni (urmăriri unidirecționale)
CREATE TABLE prieteni (
    id_user1 NUMBER(10) NOT NULL, -- urmărește
    id_user2 NUMBER(10) NOT NULL, -- este urmărit
    CONSTRAINT pk_prieteni PRIMARY KEY (id_user1, id_user2),
    CONSTRAINT fk_user1 FOREIGN KEY (id_user1) REFERENCES utilizatori(id_utilizator),
    CONSTRAINT fk_user2 FOREIGN KEY (id_user2) REFERENCES utilizatori(id_utilizator),
    CONSTRAINT chk_not_self_friend CHECK (id_user1 != id_user2)
);

-- Tabelul postari
CREATE TABLE postari (
    id_postare NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user NUMBER(10) NOT NULL,
    continut VARCHAR2(1000),
    data_postarii DATE DEFAULT SYSDATE,
    CONSTRAINT fk_postare_user FOREIGN KEY (id_user) REFERENCES utilizatori(id_utilizator)
);

